// Copies the shared CBM core into the static assets so the embeddable calculator
// runs exactly the same code as the API. Wrangler runs this before dev and deploy.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const BANNER = '// GENERATED by scripts/build-assets.mjs from src/core/cbm.js. Do not edit.\n';

const source = await readFile(path.join(ROOT, 'src/core/cbm.js'), 'utf8');
await writeFile(path.join(ROOT, 'public/embed/cbm-core.js'), BANNER + source);
console.log('build-assets: public/embed/cbm-core.js updated');
